with open('main.tex', 'r', encoding='utf-8') as f:
    tex = f.read()

idx_bib1 = tex.find('\\begin{thebibliography}{99}')
idx_bib2 = tex.find('\\end{thebibliography}') + len('\\end{thebibliography}')

